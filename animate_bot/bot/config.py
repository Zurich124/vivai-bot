import os
from dataclasses import dataclass


@dataclass
class Config:
    bot_token: str
    db_path: str = "bot.db"
    preview_video_path: str = "bot/assets/preview.mp4"
    animation_video_path: str = "bot/assets/animation.mp4"
    result_video_path: str = "bot/assets/result.mp4"
    app_dir: str = "bot/assets/app"


def load_config() -> Config:
    token = os.getenv("BOT_TOKEN")
    if not token:
        raise RuntimeError(
            "Не найден BOT_TOKEN. Задайте переменную окружения BOT_TOKEN "
            "(например через .env файл или экспорт в терминале)."
        )
    return Config(bot_token=token)


